// Builds js/data/curriculum.json and js/data/aspects.json from the plain-text exports of the design documents.
// Usage: node tools/build-curriculum.mjs <levels.txt> <aspects.txt>
import { readFileSync, writeFileSync } from 'node:fs';

const [levelsPath, aspectsPath] = process.argv.slice(2);
const lines = (p) => readFileSync(p, 'utf8').split(/\r?\n/).map((l) => l.trim());

// ---- curriculum: WORLD n — NAME / Level k — Name / "1.  Stage."
const worlds = [];
let w = null, lv = null;
for (const l of lines(levelsPath)) {
  let m;
  if ((m = l.match(/^WORLD (\d+) — (.+)$/))) { w = { id: +m[1], title: m[2], levels: [] }; worlds.push(w); lv = null; continue; }
  if (!w) continue;
  if (l.startsWith('FINAL GAME ARCHITECTURE')) break;
  if ((m = l.match(/^Level (\d) — (.+)$/))) { lv = { n: +m[1], name: m[2], stages: [] }; w.levels.push(lv); continue; }
  if (lv && (m = l.match(/^(\d+)\.\s+(.+?)\.?$/)) && lv.stages.length < 10 && +m[1] === lv.stages.length + 1) {
    lv.stages.push(m[2].replace(/^(Final )?Master Duel: /, ''));
  }
}
for (const x of worlds) {
  if (x.levels.length !== 6) throw new Error(`world ${x.id} has ${x.levels.length} levels`);
  for (const y of x.levels) if (y.stages.length !== 10) throw new Error(`world ${x.id} level ${y.n} has ${y.stages.length} stages`);
}
if (worlds.length !== 20) throw new Error(`expected 20 worlds, got ${worlds.length}`);
const curJson = JSON.stringify(worlds.map((x) => x.levels.map((y) => y.stages)));
writeFileSync("js/data/curriculum.json", curJson);
writeFileSync('js/data/curriculum.js', `// Generated by tools/build-curriculum.mjs — stage titles for 20 worlds × 6 levels × 10 stages.\nexport default ${curJson};\n`);

// ---- aspects: "N. World title" / "A. Section" / "1.  item."
const A = lines(aspectsPath);
const start = A.findIndex((l) => l.startsWith('PART I —'));
const end = A.findIndex((l) => l.startsWith('PART VI —'));
const aspects = [];
let cur = null, sec = null, expect = 1, last = 0;
for (let i = start; i < end; i++) {
  const l = A[i];
  let m;
  if (!l || l.startsWith('PART ') || /^-+$/.test(l)) continue;
  if ((m = l.match(/^(\d+)\.\s+(.+?)\.?$/))) {
    if (cur && +m[1] === last + 1) {
      if (!sec) { sec = { name: 'Core topics', items: [] }; cur.sections.push(sec); }
      sec.items.push(m[2]); last++; continue;
    }
    if (+m[1] === expect) { cur = { id: expect, sections: [] }; aspects.push(cur); sec = null; last = 0; expect++; continue; }
  }
  if (!cur) continue;
  if ((m = l.match(/^([A-I])\. (.+)$/))) { sec = { name: m[2], items: [] }; cur.sections.push(sec); last = 0; continue; }
  if ((m = l.match(/^- (.+?)\.?$/)) && sec) { sec.items.push(m[1]); continue; }
  if ((m = l.match(/^Game activities: (.+)$/))) { cur.activities = m[1]; last = -1; continue; }
}
// Sections that the documents give as tables or prose rather than numbered lists.
const fill = (w, name, items) => { const s = aspects[w - 1].sections.find((x) => x.name.startsWith(name)); if (s && !s.items.length) s.items = items; };
fill(7, 'Regional geography', ['Africa', 'Europe', 'Asia', 'North America', 'South America', 'Australia and Oceania', 'Antarctica']);
fill(10, 'Language-specific', ['English language', 'Spanish language', 'French language', 'Arabic', 'Russian language', 'Hebrew language', 'Italian language', 'Greek language', 'Turkish language', 'Portuguese language', 'Standard Chinese', 'Japanese language']);
fill(10, 'Language-learning game', ['Speaking with virtual characters', 'Pronunciation practice', 'Translating sentences', 'Dialogue reconstruction', 'Grammar puzzles', 'Reading stories', 'Handwriting and character formation', 'Listening tests', 'Multilingual conversations']);
fill(14, 'Music genres', ['Pop music', 'Rock music', 'Rock and roll', 'Country music', 'Reggae', 'Classical music', 'Opera', 'Rhythm and blues', 'Jazz']);
fill(14, 'Additional worldwide', ['Music of Africa', 'Afrobeat', 'Afrobeats', 'Highlife', 'Hip hop music', 'Blues', 'Gospel music', 'Music of Latin America', 'Salsa music', 'Samba', 'Bossa nova', 'Flamenco', 'Indian classical music', 'Arabic music', 'Turkish makam', 'Music of China', 'Traditional Japanese music', 'Indigenous music of North America', 'Indigenous music of Australia', 'Music of Polynesia', 'Electronic music']);
fill(16, 'Folktales', ['Anansi', 'Yoruba folktales', 'Epic of Sundiata', 'Amazigh folktales', "Aesop's Fables", 'Norse mythology', 'Arthurian legends', "Grimms' Fairy Tales", 'Slavic folklore', 'Panchatantra', 'Jataka tales', 'One Thousand and One Nights', 'Journey to the West', 'Ramayana', 'Mahabharata', 'Japanese folktales', 'Shahnameh', 'Inuit storytelling', 'Maya mythology (Popol Vuh)', 'African American folktales', 'Inca mythology', 'Guaraní mythology', 'Mapuche storytelling', 'Brazilian folklore', 'Aboriginal Australian storytelling', 'Māori mythology', 'Polynesian navigation stories', 'Hawaiian legends', 'Antarctic expedition narratives']);
if (aspects.length !== 20) throw new Error(`expected 20 aspect worlds, got ${aspects.length}`);
writeFileSync('js/data/aspects.json', JSON.stringify(aspects));
console.log('curriculum stages:', worlds.reduce((s, x) => s + x.levels.reduce((t, y) => t + y.stages.length, 0), 0));
console.log(aspects.map((a) => `${a.id}:${a.sections.length}s/${a.sections.reduce((s, x) => s + x.items.length, 0)}i`).join(' '));
